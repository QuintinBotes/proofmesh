// Generates TypeScript types from the JSON Schemas; --check fails when the committed file is out of date.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { compile } from 'json-schema-to-typescript'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'packages', 'proofmesh', 'src', 'core', 'generated.ts')
const files = ['envelope.schema.json', 'error.schema.json', 'limits.schema.json',
  ...fs.readdirSync(path.join(here, 'tools')).sort().map((f) => `tools/${f}`),
  ...fs.readdirSync(path.join(here, 'adapter-protocol')).sort().map((f) => `adapter-protocol/${f}`)]
let text = '// Generated by schemas/generate-types.mjs from schemas/. Do not edit.\n/* eslint-disable */\n'
for (const f of files) {
  const schema = JSON.parse(fs.readFileSync(path.join(here, f), 'utf8'))
  const name = f.replace(/^.*\//, '').replace(/\.schema\.json$/, '').split(/[._-]/).map((s) => s[0].toUpperCase() + s.slice(1)).join('')
  text += '\n' + (await compile({ ...schema, title: name }, name, { bannerComment: '', additionalProperties: false, strictIndexSignatures: false, format: false, declareExternallyReferenced: true, maxItems: -1 }))
}
if (process.argv.includes('--check')) {
  const current = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : ''
  if (current !== text) { console.error(`${path.relative(process.cwd(), out)} is out of date; run node schemas/generate-types.mjs`); process.exit(1) }
  console.log('generated types are current')
} else {
  fs.mkdirSync(path.dirname(out), { recursive: true })
  fs.writeFileSync(out, text)
  console.log(`wrote ${path.relative(process.cwd(), out)}`)
}
