// Generates THIRD_PARTY_NOTICES.md from the production dependency licenses (NFR013). --check fails when it is stale.
import fs from 'node:fs'
import path from 'node:path'
import { licenseReport, root } from './lib.mjs'

const rows = []
for (const [license, pkgs] of Object.entries(licenseReport())) for (const p of pkgs) if (!p.name.startsWith('@proofmesh/') && p.name !== 'proofmesh') rows.push({ name: p.name, versions: (p.versions ?? [p.version]).join(', '), license })
rows.sort((a, b) => (a.name < b.name ? -1 : 1))
let text = ['# Third-party notices', '', 'Production dependencies of the Proofmesh packages, with their licenses as declared by each package; each is published on the npm registry under its name. Generated by `pnpm release:notices`; do not edit by hand.', '', '| Package | Versions | License |', '|---|---|---|', ...rows.map((r) => `| ${r.name} | ${r.versions} | ${r.license} |`), ''].join('\n')
// Grammars are devDependencies of the syntax adapter, compiled into its package: listed here, their license texts shipped beside them.
const syntax = path.join(root, 'adapters', 'syntax')
const grammars = Object.keys(JSON.parse(fs.readFileSync(path.join(syntax, 'package.json'), 'utf8')).devDependencies ?? {}).filter((n) => /(^|\/)tree-sitter-/.test(n) && n !== 'tree-sitter-cli').sort().map((n) => {
  const meta = JSON.parse(fs.readFileSync(path.join(syntax, 'node_modules', n, 'package.json'), 'utf8'))
  return `| ${n} | ${meta.version} | ${meta.license} |`
})
text += ['', '## Grammars compiled into @proofmesh/adapter-syntax', '', "Each grammar's WebAssembly build ships in `dist/grammars/` with its license text beside it (`<language>.LICENSE`).", '', '| Package | Version | License |', '|---|---|---|', ...grammars, ''].join('\n')
const file = path.join(root, 'THIRD_PARTY_NOTICES.md')
if (process.argv.includes('--check')) {
  if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error('THIRD_PARTY_NOTICES.md is stale; run pnpm release:notices'); process.exit(1) }
  console.log(`third-party notices are current: ${rows.length} packages`)
} else {
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text)
  console.log(`wrote ${path.relative(root, file)}: ${rows.length} packages`)
}
